"""Draft generation for data/codebook.yaml (SPEC §5.2).

The LLM drafts definition, notes, examples and search terms per main criterion; name and
sub-criteria come from criteria.csv. Every generated entry has `status: draft`. Entries the
author has marked `status: reviewed` are never overwritten.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import yaml

from locassess.criteria import MainCriterion
from locassess.providers.llm import LLM

CODEBOOK_VERSION = "0.1"

FIXED_DEFINITIONS = {
    "direction_definition": "+1 = makes the location more attractive for a production site; "
                            "-1 = less attractive; 0 = mentioned without a clear direction",
    "intensity_definition": {
        1: "minor or local effect, single event",
        2: "noticeable effect on companies in the region",
        3: "major effect that would change a location decision",
    },
    "evidence_type_definition": {
        "fact": "has happened / is in force",
        "announcement": "planned, announced, decided but not yet implemented",
        "opinion": "assessment, forecast, criticism, expectation",
    },
}

DRAFT_SCHEMA = {
    "type": "object",
    "properties": {
        "definition": {"type": "string"},
        "notes": {"type": "string"},
        "positive_examples": {"type": "array", "items": {"type": "string"}},
        "negative_examples": {"type": "array", "items": {"type": "string"}},
        "search_terms": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["definition", "notes", "positive_examples", "negative_examples", "search_terms"],
    "additionalProperties": False,
}

HEADER = """\
# LocAssess codebook (SPEC §5.2)
#
# Used twice: as the model instruction in Stage 1 and as the annotation guideline for the
# manual gold standard. Entries generated by `locassess codebook-draft` have status: draft.
# Review each entry, edit it as needed, then set `status: reviewed`.
# Reviewed entries are never overwritten by `codebook-draft --force`.
# `name` and `sub_criteria` must stay identical to data/criteria.csv.
"""


def _sub_list(main: MainCriterion) -> list[str]:
    return [f"{s.sub_id} {s.name}" for s in main.sub_criteria]


def draft_entry(llm: LLM, main: MainCriterion, criteria: list[MainCriterion],
                temperature: float = 0) -> tuple[dict, str | None]:
    all_criteria = "\n".join(f"- {m.main_id} {m.name} ({m.factor})" for m in criteria)
    result = llm.complete("codebook_draft", {
        "all_criteria": all_criteria, "main_id": main.main_id, "factor": main.factor, "name": main.name,
        "sub_criteria": ", ".join(_sub_list(main)) or "(none — the main criterion is not subdivided)",
    }, json_schema=DRAFT_SCHEMA, temperature=temperature)
    d = result.parsed[0]

    def clean(items: list[str]) -> list[str]:
        return list(dict.fromkeys(" ".join(str(i).split()) for i in items if str(i).strip()))

    return {
        "status": "draft",
        "name": main.name,
        "factor": main.factor,
        "definition": " ".join(d["definition"].split()),
        "notes": " ".join(d["notes"].split()),
        "sub_criteria": _sub_list(main),
        "positive_examples": clean(d["positive_examples"]),
        "negative_examples": clean(d["negative_examples"]),
        "search_terms": clean(d["search_terms"]),
    }, result.prompt_version


def write_codebook_draft(path: str | Path, llm: LLM, criteria: list[MainCriterion], model: str,
                         force: bool = False, temperature: float = 0, progress=lambda m: None) -> list[str]:
    """Create or refresh the draft codebook. Returns the IDs of the (re)generated entries."""
    path = Path(path)
    existing: dict = {}
    if path.exists():
        if not force:
            raise FileExistsError(f"{path} exists; use --force to regenerate its draft entries "
                                  "(reviewed entries are kept)")
        existing = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    old = existing.get("criteria") or {}

    entries: dict[str, dict] = {}
    generated: list[str] = []
    prompt_version = None
    for main in criteria:
        if (old.get(main.main_id) or {}).get("status") == "reviewed":
            entries[main.main_id] = old[main.main_id]
            continue
        progress(f"drafting {main.main_id} {main.name}")
        entries[main.main_id], prompt_version = draft_entry(llm, main, criteria, temperature)
        generated.append(main.main_id)

    data = {
        "version": existing.get("version", CODEBOOK_VERSION),
        "draft_generated_with": {"model": model, "prompt": f"codebook_draft {prompt_version}",
                                 "date": date.today().isoformat()} if generated
        else existing.get("draft_generated_with"),
        **FIXED_DEFINITIONS,
        **{k: existing[k] for k in FIXED_DEFINITIONS if k in existing},   # keep the author's edits
        "criteria": entries,
    }
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100, default_flow_style=False)
    path.write_text(HEADER + "\n" + body, encoding="utf-8")
    return generated
